const {test} = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const {freePort,backendEnvironment,isLocalNavigation,health} = require('../backend.cjs')
test('desktop data and stable secret stay outside release', t => {
 const data=fs.mkdtempSync(path.join(os.tmpdir(),'fluxclaw-desktop-'))
 t.after(()=>fs.rmSync(data,{recursive:true,force:true}))
 const first=backendEnvironment(data,4321,'random-token','/python')
 const second=backendEnvironment(data,4322,'next-token','/python')
 assert.equal(first.SECRET_KEY_BASE,second.SECRET_KEY_BASE)
 assert.equal(first.PORT,'4321')
 assert.equal(first.DATABASE_PATH,path.join(data,'fluxclaw.db'))
 assert.equal(first.FLUXCLAW_DESKTOP,'1')
 assert.equal(first.FLUXCLAW_PYTHON,'/python')
 assert.equal(first.RELEASE_DISTRIBUTION,'none')
})
test('navigation policy uses exact origin and rejects foreign schemes/ports',()=>{
 assert.equal(isLocalNavigation('http://127.0.0.1:4321/chat/a','http://127.0.0.1:4321'),true)
 for (const url of ['https://evil.test','http://127.0.0.1:9999','file:///etc/passwd','javascript:alert(1)','http://127.0.0.1.evil.test:4321']) assert.equal(isLocalNavigation(url,'http://127.0.0.1:4321'),false)
})
test('chooses an ephemeral loopback port',async()=>assert.ok(await freePort()>0))
test('unavailable health endpoint is false',async()=>assert.equal(await health('http://127.0.0.1:1','token'),false))
